#!/usr/bin/env bash
#
# Bootstrap the remote Terraform state backend (Azure Blob Storage).
#
# Both root modules — terraform/ (worker VM) and terraform/aks/ (AKS) — keep
# their state as separate blobs (distinct `key`) in ONE storage container. That
# storage cannot be managed by the same Terraform runs that depend on it (chicken
# and egg), so it is created here imperatively with the az CLI.
#
# Idempotent and stateless: safe to re-run, and re-running on a fresh machine or
# a rebuilt dev container regenerates the gitignored backend.hcl files pointing
# at the SAME storage (the account name is derived from your subscription id, so
# it is stable and globally-unique-enough). This is what keeps `terraform apply`
# working across container rebuilds instead of orphaning Azure resources.
#
# Usage:
#   az login                                   # + az account set -s <id> if needed
#   ./bootstrap-backend.sh
#   cd .   && terraform init -backend-config=backend.hcl
#   cd aks && terraform init -backend-config=backend.hcl
#
# Override any default via env vars:
#   TFSTATE_LOCATION         (default: westus2)
#   TFSTATE_RESOURCE_GROUP   (default: pg-cyan-tfstate-rg)
#   TFSTATE_STORAGE_ACCOUNT  (default: pgcyantf<subscription-hash>)
#   TFSTATE_CONTAINER        (default: tfstate)
set -euo pipefail

command -v az >/dev/null 2>&1 || {
  echo "az CLI not found. Install the Azure CLI first." >&2
  exit 1
}

LOCATION="${TFSTATE_LOCATION:-westus2}"
RESOURCE_GROUP="${TFSTATE_RESOURCE_GROUP:-pg-cyan-tfstate-rg}"
CONTAINER="${TFSTATE_CONTAINER:-tfstate}"

SUBSCRIPTION_ID="$(az account show --query id -o tsv 2>/dev/null || true)"
if [ -z "$SUBSCRIPTION_ID" ]; then
  echo "Not logged in to Azure. Run 'az login' (and 'az account set -s <id>') first." >&2
  exit 1
fi

# Storage account names: 3-24 chars, lowercase alphanumeric, GLOBALLY unique.
# Derive a stable 12-char suffix from the subscription id so every machine hits
# the same account and there is nothing environment-specific to commit.
if command -v sha256sum >/dev/null 2>&1; then
  SUFFIX="$(printf '%s' "$SUBSCRIPTION_ID" | sha256sum | cut -c1-12)"
else
  SUFFIX="$(printf '%s' "$SUBSCRIPTION_ID" | shasum -a 256 | cut -c1-12)"
fi
STORAGE_ACCOUNT="${TFSTATE_STORAGE_ACCOUNT:-pgcyantf${SUFFIX}}"

echo "Subscription : $SUBSCRIPTION_ID"
echo "Resource grp : $RESOURCE_GROUP ($LOCATION)"
echo "Storage acct : $STORAGE_ACCOUNT"
echo "Container    : $CONTAINER"
echo

# 1. Resource group for the state storage (idempotent).
az group create \
  --name "$RESOURCE_GROUP" \
  --location "$LOCATION" \
  --tags project=pg_cyan managed_by=bootstrap-backend component=tfstate \
  --output none

# 2. Storage account (idempotent). Shared-key access stays enabled: the azurerm
#    backend fetches the key via ARM at init/apply time, so it never lands in the
#    repo or in your hands. Public (anonymous) blob access is turned off.
if ! az storage account show --name "$STORAGE_ACCOUNT" --resource-group "$RESOURCE_GROUP" --output none 2>/dev/null; then
  echo "Creating storage account $STORAGE_ACCOUNT ..."
  az storage account create \
    --name "$STORAGE_ACCOUNT" \
    --resource-group "$RESOURCE_GROUP" \
    --location "$LOCATION" \
    --sku Standard_LRS \
    --kind StorageV2 \
    --min-tls-version TLS1_2 \
    --allow-blob-public-access false \
    --output none
fi

# Blob versioning + 30-day soft delete so a botched apply cannot irrecoverably
# clobber state history.
az storage account blob-service-properties update \
  --account-name "$STORAGE_ACCOUNT" \
  --resource-group "$RESOURCE_GROUP" \
  --enable-versioning true \
  --enable-delete-retention true \
  --delete-retention-days 30 \
  --output none

# 3. Blob container that holds the state blobs (idempotent). Created with the
#    account key so it works for the account owner regardless of blob-data RBAC.
ACCOUNT_KEY="$(az storage account keys list --resource-group "$RESOURCE_GROUP" --account-name "$STORAGE_ACCOUNT" --query '[0].value' -o tsv)"
az storage container create \
  --name "$CONTAINER" \
  --account-name "$STORAGE_ACCOUNT" \
  --account-key "$ACCOUNT_KEY" \
  --output none

# 4. Generate the per-module backend.hcl (gitignored, like *.tfvars). The state
#    `key` is intentionally absent — it is committed in each module's
#    backend "azurerm" block.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for module_dir in "$SCRIPT_DIR" "$SCRIPT_DIR/aks"; do
  cat > "$module_dir/backend.hcl" <<EOF
# GENERATED by terraform/bootstrap-backend.sh -- do NOT commit (env-specific).
resource_group_name  = "$RESOURCE_GROUP"
storage_account_name = "$STORAGE_ACCOUNT"
container_name       = "$CONTAINER"
EOF
  echo "Wrote ${module_dir}/backend.hcl"
done

cat <<EOF

Backend ready. Initialize each module (first time, or after a container rebuild):

  cd "$SCRIPT_DIR"     && terraform init -backend-config=backend.hcl
  cd "$SCRIPT_DIR/aks" && terraform init -backend-config=backend.hcl

If a module still holds local state from an earlier run, add -migrate-state the
first time to copy it up; add -reconfigure if init complains the backend changed.
EOF
